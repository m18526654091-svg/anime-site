def main() -> None:
    # 1. 读取现有数据
    existing: list[dict] = []
    if os.path.exists(DATA_FILE):
        with open(DATA_FILE, encoding="utf-8") as f:
            existing = json.load(f)
    print(f"现有 anime_data.json: {len(existing)} 条")

    # 2. 构建已知真实动漫
    known = [
        {
            "title": t,
            "chinese_title": c,
            "year": y,
            "genre": g,
            "studio": s,
            "score": sc,
            # 信息型差异化描述（含中文名/年份/类型/制作公司），避免通用模板重复
            "description": f"《{c}》是一部{y}年首播的{g}题材日本动画，由{s}制作，凭借出色的剧情与制作深受观众喜爱，是值得一看的动漫佳作。",
        }
        for (t, c, y, g, s, sc) in KNOWN_ANIME
    ]
    print(f"内置真实知名动漫: {len(known)} 条")

    # 3. 合并去重（按 chinese_title + title）
    seen_keys: set[str] = set()
    merged: list[dict] = []
    for item in existing + known:
        key = (item.get("chinese_title") or "").strip() or (item.get("title") or "").strip()
        if not key:
            continue
        k = key.lower()
        if k in seen_keys:
            continue
        seen_keys.add(k)
        merged.append(dict(item))
    print(f"合并去重后: {len(merged)} 条")

    # 4. 不再生成"动漫典藏"等模板数据（阶段8：真实内容优先）
    #    仅使用内置真实知名动漫 + 已有数据；不足 TARGET_COUNT 时如实保留，
    #    绝不硬凑模板条目。
    if len(merged) < TARGET_COUNT:
        print(f"警告: 真实动漫仅 {len(merged)} 条，不足目标 {TARGET_COUNT}，不再生成模板补足。")

    # 5. 补齐 SEO 字段
    final = [_fill(d) for d in merged]
    final = final[:TARGET_COUNT]

    # 6. 写回
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(final, f, ensure_ascii=False, indent=2)
    print(f"已写出: {DATA_FILE} ({len(final)} 条)")

    # 7. 快速自检
    titles = [d.get("title") for d in final]
    cn_titles = [d.get("chinese_title") for d in final]
    dup_title = len(titles) - len(set(titles))
    dup_cn = len(cn_titles) - len(set(cn_titles))
    missing = {
        f: sum(1 for d in final if d.get(f) is None or str(d.get(f) or "").strip() == "")
        for f in ("title", "chinese_title", "genre", "tags", "year", "studio")
    }
    print(f"重复 title: {dup_title}, 重复 chinese_title: {dup_cn}")
    print(f"缺失字段: {missing}")


if __name__ == "__main__":
    main()


