def _fill(item: dict) -> dict:
    """补齐缺失字段，保证 SEO 完整性。"""
    title = (item.get("title") or "").strip()
    cn = (item.get("chinese_title") or "").strip() or title
    item["title"] = title
    item["chinese_title"] = cn
    item.setdefault("region", "日本")
    item.setdefault("status", "完结")
    item.setdefault("tags", "/".join(g.strip() for g in (item.get("genre") or "").split("/") if g.strip()))
    item.setdefault("author", "原作")
    item.setdefault("score", 7.0)
    item.setdefault("episodes", 12)
    item.setdefault("year", 2020)
    item.setdefault("studio", "MADHOUSE")
    item.setdefault("description", f"{cn}：一部值得一看的动漫作品，讲述{cn}的精彩故事，在线观看高清全集。")
    if not (item.get("cover") or "").strip():
        item["cover"] = f"https://placehold.co/360x480/1a1a2e/e94560?text={cn}"
    seed = sum(ord(c) for c in cn)
    item["month"] = (seed % 12) + 1
    return item


